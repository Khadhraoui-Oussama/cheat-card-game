	socket.on("disconnect", (reason) => {
		console.log(`Socket with ID ${socket.id} has disconnected, reason: ${reason}`);

		Object.keys(onlineUsers).forEach((roomCode) => {
			const player = playersInRoom(roomCode).find((seatedPlayer) => seatedPlayer.socketID === socket.id);
			if (!player) return;

			const meta = getRoomMeta(roomCode);

			// In the lobby there is no state worth preserving - free the seat.
			if (!meta.gameStarted) {
				removePlayer(roomCode, player.playerId);
				return;
			}

			// Mid game the seat (and the hand that goes with it) is held open.
			player.connected = false;
			player.disconnectedAt = Date.now();
			pauseRoomTimer(roomCode);

			io.to(roomCode).emit("playerConnectionChanged", {
				playerId: player.playerId,
				name: player.name,
				connected: false,
				graceSeconds: RECONNECT_GRACE_SECONDS,
			});
			io.to(roomCode).emit("updateUserList", onlineUsers[roomCode]);
			sendSystemMessage(roomCode, `${player.name} lost connection. Holding their seat for ${RECONNECT_GRACE_SECONDS}s…`);

			cancelPendingRemoval(player.playerId);
			pendingRemovals.set(
				player.playerId,
				setTimeout(() => {
					pendingRemovals.delete(player.playerId);

					const stillMissing = playersInRoom(roomCode).find((seatedPlayer) => seatedPlayer.playerId === player.playerId && seatedPlayer.connected === false);
					if (!stillMissing) return; // they made it back in time

					// Four players are required, so rather than throwing the round
					// away the chair is held open - with the hand still on it - for
					// whoever sits down next, the original player included.
					openSeat(roomCode, stillMissing, `${player.name} did not come back. Their seat is open - share the code ${roomCode} and the game picks up where it stopped.`);
				}, RECONNECT_GRACE_SECONDS * 1000)
			);
		});
	});

	// Add handler for manual quit
	socket.on("leaveRoom", (roomCode) => {
		socket.leave(roomCode);

		const leavingPlayer = playersInRoom(roomCode).find((user) => user.socketID === socket.id);
		if (!leavingPlayer) return;

		const meta = getRoomMeta(roomCode);

		// Quitting is deliberate, so there is no grace period to wait out - but
		// the chair (and the hand on it) still stays at the table for whoever
		// takes it next. Only an unstarted lobby frees a seat outright.
		if (meta.gameStarted) {
			openSeat(roomCode, leavingPlayer, `${leavingPlayer.name} left the table. Their seat is open - share the code ${roomCode} to fill it.`);
			return;
		}

		removePlayer(roomCode, leavingPlayer.playerId);
	});

	socket.on("usePowerup", ({type, powerupId, roomCode, userId, targetId}) => {
		if (rejectWhilePaused(roomCode)) return;

		const player = onlineUsers[roomCode]?.find((p) => p.socketID === userId);
		const targetPlayer = onlineUsers[roomCode]?.find((p) => p.socketID === targetId);

		if (!player || player.powerups[powerupId] <= 0) {
			return;
		}

		// Nothing to cleanse means nothing to spend a cleanse on.
		if (type === "cleanse" && !player.preOrderInfo?.isPreordered) {
			io.to(userId).emit("updateGameEventMessage", "Nobody has preordered you — there is nothing to cleanse.");
			return;
		}

		// Reduce powerup count
		player.powerups[powerupId]--;

		// Notify client about powerup consumption
		io.to(userId).emit("powerupUsed", {type, powerupId});

		switch (type) {
			case "trueVision":
				if (targetPlayer) {
					// Send cards only to the player who used the powerup
					//don't send all cards , rather send a precentage of the cards
					const PERCENTAGE_OF_CARDS_TO_SEE = 0.3;
					const cardsToSend = Math.max(Math.floor(targetPlayer.cards.length * PERCENTAGE_OF_CARDS_TO_SEE), 1);
					io.to(userId).emit("revealCards", {
						cards: targetPlayer.cards.slice(0, cardsToSend),
						playerName: targetPlayer.name,
					});
					console.log("True Vision used on:", targetPlayer.name);
					// Notify room about powerup use
					io.to(roomCode).emit("updateGameEventMessage", `${player.name} used True Vision on ${targetPlayer.name}!`);
				}
				break;

			case "skipPlayer":
				const currentTurnPlayer = onlineUsers[roomCode].find((p) => p.hasTurn)?.socketID;
				if (targetPlayer && targetPlayer.socketID === currentTurnPlayer) {
					const nextPlayer = findNextTurn(targetId, roomCode);
					handleTurnChange(roomCode, nextPlayer.socketID, targetPlayer, false);

					// Decrement powerup count since it was used successfully
					player.powerups[powerupId]--;
					io.to(roomCode).emit("updateGameEventMessage", `${player.name} skipped ${targetPlayer.name}'s turn!`);

					// Notify about powerup usage
					io.to(userId).emit("powerupUsed", {type: "skipPlayer", powerupId});
				} else {
					// Send error message only to the player who tried to use the powerup
					io.to(userId).emit("updateGameEventMessage", `Can't skip ${targetPlayer.name}'s turn as they don't have the current turn!`);
				}
				break;

			case "cleanse": {
				// The claim is off this player - and the one claim its owner was
				// allowed goes back to them, or they could never preorder again.
				const meta = getRoomMeta(roomCode);
				const claimOwner = onlineUsers[roomCode]?.find((p) => p.socketID === player.preOrderInfo?.playerWhoPreordered);
				player.preOrderInfo = {isPreordered: false, playerWhoPreordered: null};
				if (meta.lastPlayedSocketID === player.socketID) {
					meta.lastPlayedSocketID = null;
					io.to(roomCode).emit("updateTurn", {
						currentPlayer: meta.currentTurnSocketID,
						lastPlayedPlayer: null,
						currentCardValue: meta.currentCardValue,
						newTurnStatus: meta.isNewTurn,
					});
				}
				if (claimOwner) {
					claimOwner.issuedPreorderDetails = {hasIssuedPreorder: false, playerIssuedAgainstID: null};
					io.to(claimOwner.socketID).emit("updateLocalPlayer", claimOwner);
				}
				io.to(userId).emit("updateLocalPlayer", player);
				broadcastPreorders(roomCode);
				io.to(roomCode).emit("updateGameEventMessage", `${player.name} cleansed all preorders!`);
				break;
			}
		}

		// Update powerup state for user
		io.to(userId).emit("updateLocalPlayer", player);
	});

