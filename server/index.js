	socket.on("attemptReconnect", ({roomCode, playerId}) => {
		try {
			console.log("Reconnect attempt for player", playerId, "in room", roomCode);

			const room = onlineUsers[roomCode];
			if (!room || room.length === 0) {
				socket.emit("reconnectionFailed", {reason: "room-gone", message: "That game no longer exists."});
				return;
			}

			const player = room.find((seatedPlayer) => seatedPlayer.playerId === playerId);
			if (!player) {
				socket.emit("reconnectionFailed", {reason: "seat-lost", message: "Your seat at that table is gone."});
				return;
			}

			const previousSocketID = player.socketID;
			const meta = getRoomMeta(roomCode);
			// Read before we flip them: socket.io's connectionStateRecovery can hand
			// back the *same* socket id, so the id alone cannot tell a real
			// reconnection from the harmless resync every client sends on connect.
			// A handover (joinRoom just sat somebody new in this chair) counts as
			// a real one too - the board has to be re-broadcast for the new id.
			const isHandover = player.pendingHandover === true;
			const reclaimedOpenSeat = player.awaitingReplacement === true;
			const wasAway = player.connected === false || isHandover;

			player.socketID = socket.id;
			player.connected = true;
			delete player.disconnectedAt;
			delete player.awaitingReplacement;
			delete player.pendingHandover;
			socket.join(roomCode);
			cancelPendingRemoval(playerId);

			// Everything that was keyed on the old socket id has to follow the player
			// to their new one, or the game would keep talking to a dead socket.
			rebindSeatSocket(roomCode, previousSocketID, socket.id);

			// Hand the returning player the whole board back. Their own hand is
			// included; everybody else's is stripped - the roster only needs
			// identity and public state to redraw the table.
			const roster = room.map(({cards, ...publicState}) => publicState);

			socket.emit("reconnectionSuccessful", {
				player,
				players: roster,
				gameStarted: meta.gameStarted,
				currentTurnSocketID: meta.currentTurnSocketID,
				lastPlayedSocketID: meta.lastPlayedSocketID,
				currentCardValue: meta.currentCardValue,
				isNewTurn: meta.isNewTurn,
				timeLeft: roomTimers.get(roomCode)?.timeLeft ?? 0,
				pileCount: (pileOfCardsInEachRoom[roomCode] ?? []).length,
				preorders: preorderSummary(roomCode),
				chatHistory: chatHistory.get(roomCode) ?? [],
			});

			// The client re-syncs on every connect, including the first one when it
			// walks in from the waiting area. That is not a reconnection, so only
			// tell the rest of the room when the player was genuinely away.
			const isRealReconnect = wasAway || previousSocketID !== socket.id;
			if (isRealReconnect) {
				io.to(roomCode).emit("playerConnectionChanged", {playerId, name: player.name, connected: true});
				io.to(roomCode).emit("updateUserList", room);
				// A handover was already announced by joinRoom, under the name of
				// whoever gave the chair up.
				if (!isHandover) sendSystemMessage(roomCode, `${player.name} reconnected.`);
			}

			// The room was waiting on this chair - tell it the wait is over.
			if (reclaimedOpenSeat) {
				io.to(roomCode).emit("seatFilled", {
					playerId,
					name: player.name,
					openSeats: openSeatSummary(roomCode),
				});
			}

			if (isRealReconnect && meta.gameStarted && everyoneIsConnected(roomCode)) {
				// Re-broadcast the turn so every other client swaps the dead socket
				// id for the new one, then let the clock run again.
				io.to(roomCode).emit("updateTurn", {
					currentPlayer: meta.currentTurnSocketID,
					lastPlayedPlayer: meta.lastPlayedSocketID,
					currentCardValue: meta.currentCardValue,
					newTurnStatus: meta.isNewTurn,
				});
				resumeRoomTimer(roomCode);
			}
		} catch (error) {
			console.error("Reconnection error:", error);
			socket.emit("reconnectionFailed", {reason: "error", message: "Something went wrong reconnecting."});
		}
	});

