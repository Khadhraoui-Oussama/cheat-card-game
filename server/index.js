/*
	The clock is pausable: while anybody in the room is mid-reconnect the
	turn must not tick down, otherwise a player loses their turn to a
	network blip they had no way to react to.
*/
const clearRoomTimer = (roomCode) => {
	const timer = roomTimers.get(roomCode);
	if (timer?.intervalId) clearInterval(timer.intervalId);
	roomTimers.delete(roomCode);
};

const runRoomTimer = (roomCode) => {
	const timer = roomTimers.get(roomCode);
	if (!timer || timer.intervalId) return;

	timer.paused = false;
	timer.intervalId = setInterval(() => {
		timer.timeLeft--;

		// Send updated time to all clients in room
		io.to(roomCode).emit("updateTimer", timer.timeLeft);

		// When timer reaches 0
		if (timer.timeLeft <= 0) {
			clearRoomTimer(roomCode);

			const currentPlayer = playersInRoom(roomCode).find((p) => p.socketID === timer.playerSocket);
			if (currentPlayer) {
				// Signal client to return cards
				io.to(timer.playerSocket).emit("turnTimedOut");

				// Find and give turn to next player, indicating no cards were played
				const nextPlayer = findNextTurn(timer.playerSocket, roomCode);
				handleTurnChange(roomCode, nextPlayer.socketID, currentPlayer, false);

				io.to(roomCode).emit("updateGameEventMessage", `${currentPlayer.name}'s turn timed out without playing any cards!`);
			}
		}
	}, 1000);
};

const startRoomTimer = (roomCode, currentPlayerSocket) => {
	clearRoomTimer(roomCode);
	roomTimers.set(roomCode, {intervalId: null, playerSocket: currentPlayerSocket, timeLeft: TURN_DURATION, paused: false});

	// Initialize timer for all clients
	io.to(roomCode).emit("updateTimer", TURN_DURATION);

	if (everyoneIsConnected(roomCode)) {
		runRoomTimer(roomCode);
	} else {
		roomTimers.get(roomCode).paused = true;
	}
};

const pauseRoomTimer = (roomCode) => {
	const timer = roomTimers.get(roomCode);
	if (!timer?.intervalId) return;
	clearInterval(timer.intervalId);
	timer.intervalId = null;
	timer.paused = true;
};

const resumeRoomTimer = (roomCode) => {
	const timer = roomTimers.get(roomCode);
	if (!timer || timer.intervalId || timer.timeLeft <= 0) return;
	io.to(roomCode).emit("updateTimer", timer.timeLeft);
	runRoomTimer(roomCode);
};

