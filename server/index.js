const getRoomMeta = (roomCode) => {
	if (!roomMeta.has(roomCode)) {
		roomMeta.set(roomCode, {gameStarted: false, currentTurnSocketID: null, lastPlayedSocketID: null, currentCardValue: null, isNewTurn: false});
	}
	return roomMeta.get(roomCode);
};

const playersInRoom = (roomCode) => onlineUsers[roomCode] ?? [];
// A seat held open for somebody who dropped is not a seat quick match can sell.
const seatedCount = (roomCode) => playersInRoom(roomCode).filter((player) => player.connected !== false).length;
const everyoneIsConnected = (roomCode) => playersInRoom(roomCode).every((player) => player.connected !== false);

/*
	A player who is gone for good is not deleted from the room: the hand in
	front of their chair is still in play. The seat is marked
	`awaitingReplacement` instead, and the room sits frozen until somebody -
	the original player, or a newcomer - sits down in it.
*/
const openSeatsInRoom = (roomCode) => playersInRoom(roomCode).filter((player) => player.awaitingReplacement);
const openSeatSummary = (roomCode) => openSeatsInRoom(roomCode).map(({playerId, name}) => ({playerId, name}));

// What a joiner can be sold: a vacated chair mid game, a free slot in a lobby.
const freeSeatCount = (roomCode) => {
	if (roomMeta.get(roomCode)?.gameStarted) return openSeatsInRoom(roomCode).length;
	return MAX_PLAYERS_PER_ROOM - playersInRoom(roomCode).length;
};

// Nothing may advance the turn while a chair is empty, or the game would deal
